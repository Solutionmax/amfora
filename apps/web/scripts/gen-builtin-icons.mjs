// Writes src/components/ui/builtin-icons.ts: the drawings of the icons the default sign-in providers use,
// copied out of react-icons so that showing them does not load a whole icon pack.
// Run from apps/web after changing the list:
//   node scripts/gen-builtin-icons.mjs && pnpm prettier --write src/components/ui/builtin-icons.ts
import { writeFileSync } from "node:fs";

const ICONS = {
  bs: ["BsFillPSquareFill"],
  fa: ["FaCog", "FaDiscord", "FaEgg", "FaKey", "FaShieldAlt"],
  fa6: ["FaShield"],
  fc: ["FcGoogle"],
  si: ["SiAuth0", "SiGithub"],
};

const out = {};
for (const [pack, names] of Object.entries(ICONS)) {
  const mod = await import(`react-icons/${pack}`);
  for (const name of names) {
    const match = /GenIcon\((\{.*\})\)\(props\)/s.exec(String(mod[name]));
    if (!match) throw new Error(`cannot read ${name} from react-icons/${pack}`);
    out[name] = JSON.parse(match[1]);
  }
}

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  "src/components/ui/builtin-icons.ts",
  `// Generated by scripts/gen-builtin-icons.mjs from react-icons. Do not edit by hand.
// Bootstrap Icons (MIT), Font Awesome Free (CC BY 4.0), Flat Color Icons (MIT), Simple Icons (CC0).
export interface IconNode {
  tag: string;
  attr: Record<string, string>;
  child?: IconNode[];
}

export const BUILTIN_ICONS: Record<string, IconNode> = ${JSON.stringify(sorted)};
`
);
console.log(`wrote ${Object.keys(sorted).length} icons`);
